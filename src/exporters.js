// Helper: converts a MultiPolygon array to an SVG path d attribute string
function multiPolyToPath(multiPoly) {
  let d = '';
  for (const poly of multiPoly) {
    for (const ring of poly) {
      if (!ring || ring.length === 0) continue;
      d += `M ${ring[0][0].toFixed(2)} ${ring[0][1].toFixed(2)} `;
      for (let i = 1; i < ring.length; i++) {
        d += `L ${ring[i][0].toFixed(2)} ${ring[i][1].toFixed(2)} `;
      }
      d += 'Z ';
    }
  }
  return d.trim();
}

// Produces clean 2D vector SVG with hidden face culling and polygon clipping
export const toSVG = function (polyIn, options = {}) {
  const width = options.width || 720;
  const height = options.height || 500;
  const xOffset = width / 2;
  const yOffset = height / 2;
  const rotM = options.rotM || clone(eye3);
  const tvec = options.tvec || [0, 0, 3];
  const pPalette = options.palette || defaultPalette;
  const paintMode = options.paintMode || 'fillstroke';
  const cullHidden = options.cullHidden !== false;
  const scale = options.perspective_scale || 1200;
  const zMax = options.persp_z_max || 5;
  const zMin = options.persp_z_min || 0;
  const pRatio = options.persp_ratio || 0.8;
  const cutoff = options.visibility_cutoff !== undefined ? options.visibility_cutoff : -0.1;

  // Clone polyhedron so input geometry is not mutated
  const poly = clone(polyIn);
  poly.vertices = poly.vertices.map(v => add(mv3(rotM, v), tvec));

  // Sort faces back-to-front carefully (Painter's order)
  try {
    sortFaces(poly, 'CAREFUL');
  } catch (e) {
    sortFaces(poly, 'FAST');
  }

  const diffFn = (polygonclipping && polygonclipping.difference) ||
    (martinez && martinez.diff);
  const unionFn = (polygonclipping && polygonclipping.union) ||
    (martinez && martinez.union);

  // Extract visible 2D faces with their shading and colors
  const visibleFaces = [];
  for (let fno = 0; fno < poly.faces.length; fno++) {
    if (!poly.visibility[fno]) continue;
    const face = poly.faces[fno];
    const face_verts = face.map(v => poly.vertices[v]);
    const norm = normal(face_verts);
    if (norm[2] <= cutoff) continue;

    // 2D projected ring (closed ring for polygon-clipping / SVG)
    const ring2d = face.map(v => {
      const [px, py] = perspT(poly.vertices[v], zMax, zMin, pRatio, scale);
      return [px + xOffset, py + yOffset];
    });
    const ring2dClosed = ring2d.concat([ring2d[0]]);

    // Calculate cosine illumination and color
    let clr;
    if (typeof pPalette === 'function') {
      clr = pPalette(poly.face_classes[fno]);
    } else if (Array.isArray(pPalette)) {
      clr = defaultPalette(poly.face_classes[fno], pPalette);
    } else {
      clr = defaultPalette(poly.face_classes[fno]);
    }
    const illum = dot(norm, unit([1, -1, 0]));
    clr = mult((((illum / 2.0) + 0.5) * 0.7) + 0.3, clr);
    const r = round(clr[0] * 255);
    const g = round(clr[1] * 255);
    const b = round(clr[2] * 255);
    const fillClr = `rgb(${r},${g},${b})`;

    visibleFaces.push({
      fno,
      face,
      ring2dClosed,
      fillClr,
      clr
    });
  }

  const svgPaths = [];

  if (cullHidden && diffFn && unionFn) {
    // Process front-to-back (from highest z / foreground down to background)
    let occluderMask = [];

    for (let i = visibleFaces.length - 1; i >= 0; i--) {
      const vf = visibleFaces[i];
      const subjectPoly = [[[ ...vf.ring2dClosed ]]];

      let visibleRegion;
      if (occluderMask.length === 0) {
        visibleRegion = subjectPoly;
      } else {
        try {
          visibleRegion = diffFn(subjectPoly, occluderMask);
        } catch (e) {
          visibleRegion = subjectPoly;
        }
      }

      if (visibleRegion && visibleRegion.length > 0) {
        const d = multiPolyToPath(visibleRegion);
        if (d.length > 0) {
          svgPaths.push({
            d,
            fillClr: vf.fillClr
          });
        }
        // Accumulate face into occluder mask
        try {
          if (occluderMask.length === 0) {
            occluderMask = subjectPoly;
          } else {
            occluderMask = unionFn(occluderMask, subjectPoly);
          }
        } catch (e) {
          // ignore union failures
        }
      }
    }
    // Re-reverse paths back to back-to-front order for natural layer rendering
    svgPaths.reverse();
  } else {
    // Standard back-to-front rendering without 2D polygon subtraction
    for (let i = 0; i < visibleFaces.length; i++) {
      const vf = visibleFaces[i];
      const d = multiPolyToPath([[[ ...vf.ring2dClosed ]]]);
      if (d.length > 0) {
        svgPaths.push({
          d,
          fillClr: vf.fillClr
        });
      }
    }
  }

  // Construct SVG output
  let strokeAttr = '';
  if (paintMode === 'fillstroke') {
    strokeAttr = 'stroke="rgba(0,0,0,0.3)" stroke-width="0.5"';
  } else if (paintMode === 'stroke') {
    strokeAttr = 'stroke="rgba(0,0,0,0.8)" stroke-width="0.5"';
  } else {
    strokeAttr = 'stroke="none"';
  }

  let svg = `<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">
  <title>Polyhedronisme SVG - ${poly.name || 'Polyhedron'}</title>
  <g fill-rule="evenodd" stroke-linejoin="round" stroke-linecap="round" ${strokeAttr}>
`;

  for (const pathObj of svgPaths) {
    const fillStr = (paintMode === 'stroke') ? 'none' : pathObj.fillClr;
    svg += `    <path d="${pathObj.d}" fill="${fillStr}" />\n`;
  }

  svg += `  </g>
</svg>
`;

  return svg;
};

// Produces binary STL (ArrayBuffer) or ASCII STL (string when options.ascii === true)
export const toSTL = function (poly, options = {}) {
  const scale = options.scale || 1.0;
  const tris = [];

  for (let i = 0; i < poly.faces.length; i++) {
    const f = poly.faces[i];
    if (f.length < 3) continue;
    const faceVerts = f.map(v => poly.vertices[v]);
    const norm = normal(faceVerts);

    if (f.length === 3) {
      tris.push({
        norm,
        v0: poly.vertices[f[0]],
        v1: poly.vertices[f[1]],
        v2: poly.vertices[f[2]]
      });
    } else {
      const face2d = project2dface(faceVerts);
      const localTris = earClipTriangulate(face2d);
      for (let j = 0; j < localTris.length; j++) {
        const [a, b, c] = localTris[j];
        tris.push({
          norm,
          v0: poly.vertices[f[a]],
          v1: poly.vertices[f[b]],
          v2: poly.vertices[f[c]]
        });
      }
    }
  }

  if (options.ascii) {
    const safeName = (poly.name || 'polyhedron').replace(/\s+/g, '_');
    let stl = `solid ${safeName}\n`;
    for (const t of tris) {
      stl += `  facet normal ${t.norm[0]} ${t.norm[1]} ${t.norm[2]}\n`;
      stl += '    outer loop\n';
      stl += `      vertex ${t.v0[0] * scale} ${t.v0[1] * scale} ${t.v0[2] * scale}\n`;
      stl += `      vertex ${t.v1[0] * scale} ${t.v1[1] * scale} ${t.v1[2] * scale}\n`;
      stl += `      vertex ${t.v2[0] * scale} ${t.v2[1] * scale} ${t.v2[2] * scale}\n`;
      stl += '    endloop\n';
      stl += '  endfacet\n';
    }
    stl += `endsolid ${safeName}\n`;
    return stl;
  }

  // Binary STL: 80-byte header + 4-byte uint32 count + 50 bytes per triangle
  const buffer = new ArrayBuffer(84 + (tris.length * 50));
  const headerBytes = new Uint8Array(buffer, 0, 80);
  const headerText = `Generated by Polyhedronisme - ${poly.name || 'polyhedron'}`;
  for (let i = 0; i < Math.min(79, headerText.length); i++) {
    headerBytes[i] = headerText.charCodeAt(i) & 0x7f;
  }

  const view = new DataView(buffer);
  view.setUint32(80, tris.length, true);

  let offset = 84;
  for (let i = 0; i < tris.length; i++) {
    const { norm, v0, v1, v2 } = tris[i];
    view.setFloat32(offset, norm[0], true);
    view.setFloat32(offset + 4, norm[1], true);
    view.setFloat32(offset + 8, norm[2], true);

    view.setFloat32(offset + 12, v0[0] * scale, true);
    view.setFloat32(offset + 16, v0[1] * scale, true);
    view.setFloat32(offset + 20, v0[2] * scale, true);

    view.setFloat32(offset + 24, v1[0] * scale, true);
    view.setFloat32(offset + 28, v1[1] * scale, true);
    view.setFloat32(offset + 32, v1[2] * scale, true);

    view.setFloat32(offset + 36, v2[0] * scale, true);
    view.setFloat32(offset + 40, v2[1] * scale, true);
    view.setFloat32(offset + 44, v2[2] * scale, true);

    view.setUint16(offset + 48, 0, true);
    offset += 50;
  }

  return buffer;
};

// Pure-JS minimal uncompressed PNG encoder for embedding a palette texture strip in GLB
const crc32Table = (() => {
  const table = new Uint32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) {
      c = (c & 1) ? (0xedb88320 ^ (c >>> 1)) : (c >>> 1);
    }
    table[n] = c >>> 0;
  }
  return table;
})();

function crc32(bytes, start = 0, length = bytes.length - start) {
  let c = 0xffffffff;
  for (let i = start; i < start + length; i++) {
    c = crc32Table[(c ^ bytes[i]) & 0xff] ^ (c >>> 8);
  }
  return (c ^ 0xffffffff) >>> 0;
}

function adler32(bytes) {
  let a = 1;
  let b = 0;
  for (let i = 0; i < bytes.length; i++) {
    a = (a + bytes[i]) % 65521;
    b = (b + a) % 65521;
  }
  return ((b << 16) | a) >>> 0;
}

function encodePalettePNG(palColors, swatchSize = 8) {
  const numColors = Math.max(1, palColors.length);
  const width = numColors * swatchSize;
  const height = swatchSize;

  // Raw scanlines: each row starts with filter byte 0x00 followed by RGB triples
  const rowStride = 1 + (width * 3);
  const rawData = new Uint8Array(height * rowStride);
  const rgbSwatches = [];
  for (let k = 0; k < numColors; k++) {
    const clr = defaultPalette(k, palColors);
    rgbSwatches.push([
      Math.max(0, Math.min(255, round(clr[0] * 255))),
      Math.max(0, Math.min(255, round(clr[1] * 255))),
      Math.max(0, Math.min(255, round(clr[2] * 255)))
    ]);
  }

  for (let y = 0; y < height; y++) {
    const rowOffset = y * rowStride;
    rawData[rowOffset] = 0; // filter type 0 (None)
    let p = rowOffset + 1;
    for (let k = 0; k < numColors; k++) {
      const [r, g, b] = rgbSwatches[k];
      for (let sx = 0; sx < swatchSize; sx++) {
        rawData[p++] = r;
        rawData[p++] = g;
        rawData[p++] = b;
      }
    }
  }

  // Wrap rawData in a zlib stream with an uncompressed Deflate store block (rawData.length <= 65535)
  const blockLen = rawData.length;
  const nlen = (~blockLen) & 0xffff;
  const zlibData = new Uint8Array(2 + 5 + blockLen + 4);
  zlibData[0] = 0x78; // CMF
  zlibData[1] = 0x01; // FLG
  zlibData[2] = 0x01; // BFINAL=1, BTYPE=00 (uncompressed)
  zlibData[3] = blockLen & 0xff;
  zlibData[4] = (blockLen >>> 8) & 0xff;
  zlibData[5] = nlen & 0xff;
  zlibData[6] = (nlen >>> 8) & 0xff;
  zlibData.set(rawData, 7);
  const adler = adler32(rawData);
  const adlerView = new DataView(zlibData.buffer);
  adlerView.setUint32(7 + blockLen, adler, false);

  const makeChunk = (typeStr, dataBytes) => {
    const chunk = new Uint8Array(12 + dataBytes.length);
    const dv = new DataView(chunk.buffer);
    dv.setUint32(0, dataBytes.length, false);
    for (let i = 0; i < 4; i++) {
      chunk[4 + i] = typeStr.charCodeAt(i);
    }
    chunk.set(dataBytes, 8);
    const crc = crc32(chunk, 4, 4 + dataBytes.length);
    dv.setUint32(8 + dataBytes.length, crc, false);
    return chunk;
  };

  const ihdrData = new Uint8Array(13);
  const ihdrView = new DataView(ihdrData.buffer);
  ihdrView.setUint32(0, width, false);
  ihdrView.setUint32(4, height, false);
  ihdrData[8] = 8; // bit depth 8
  ihdrData[9] = 2; // color type 2 (truecolor RGB)
  ihdrData[10] = 0; // compression
  ihdrData[11] = 0; // filter
  ihdrData[12] = 0; // interlace

  const pngSig = new Uint8Array([137, 80, 78, 71, 13, 10, 26, 10]);
  const ihdrChunk = makeChunk('IHDR', ihdrData);
  const idatChunk = makeChunk('IDAT', zlibData);
  const iendChunk = makeChunk('IEND', new Uint8Array(0));

  const png = new Uint8Array(pngSig.length + ihdrChunk.length + idatChunk.length + iendChunk.length);
  let offset = 0;
  png.set(pngSig, offset); offset += pngSig.length;
  png.set(ihdrChunk, offset); offset += ihdrChunk.length;
  png.set(idatChunk, offset); offset += idatChunk.length;
  png.set(iendChunk, offset);
  return png;
}

// Converts an sRGB channel in [0, 1] to linear-light RGB per IEC 61966-2-1 (glTF 2.0 spec)
function srgbToLinear(c) {
  if (c <= 0.04045) return c / 12.92;
  return Math.pow((c + 0.055) / 1.055, 2.4);
}

// Produces binary glTF 2.0 (.glb) ArrayBuffer with flat-shaded normals, per-face-class PBR materials,
// planar per-face UV coordinates, and an embedded neutral PNG texture
export const toGLB = function (polyIn, pal, options = {}) {
  const scale = options.scale || 1.0;
  const palColors = (Array.isArray(pal) && pal.length > 0) ? pal : rwb_palette;

  let poly = polyIn;
  if (!Array.isArray(poly.face_classes) || poly.face_classes.length !== poly.faces.length) {
    poly = paintPolyhedron(clone(polyIn));
  }

  // Group faces by face_class so each symmetry class gets its own glTF material & primitive
  const classToGroup = new Map();
  const groups = [];

  for (let fno = 0; fno < poly.faces.length; fno++) {
    const f = poly.faces[fno];
    if (f.length < 3) continue;

    const fc = poly.face_classes[fno] !== undefined ? poly.face_classes[fno] : (f.length - 3);
    let grp = classToGroup.get(fc);
    if (!grp) {
      const srgb = defaultPalette(fc, palColors);
      const hex = floatstohex(srgb);
      grp = {
        fc,
        hex,
        baseColorFactor: [
          srgbToLinear(srgb[0]),
          srgbToLinear(srgb[1]),
          srgbToLinear(srgb[2]),
          1.0
        ],
        faces: []
      };
      classToGroup.set(fc, grp);
      groups.push(grp);
    }
    grp.faces.push(f);
  }

  // Collect shared vertex streams (POSITION, NORMAL, TEXCOORD_0) and per-material index buffers
  const posList = [];
  const normList = [];
  const uvList = [];
  const groupIdxArrays = [];
  let vertCount = 0;

  for (let g = 0; g < groups.length; g++) {
    const grp = groups[g];
    const idxList = [];

    for (let i = 0; i < grp.faces.length; i++) {
      const f = grp.faces[i];
      const faceVerts = f.map(v => poly.vertices[v]);
      const fnorm = normal(faceVerts);
      const face2d = project2dface(faceVerts);

      // Compute normalized [0, 1] planar UVs for the polygon face
      let minU = Infinity;
      let minV = Infinity;
      let maxU = -Infinity;
      let maxV = -Infinity;
      for (let j = 0; j < face2d.length; j++) {
        const [u, v] = face2d[j];
        if (u < minU) minU = u;
        if (v < minV) minV = v;
        if (u > maxU) maxU = u;
        if (v > maxV) maxV = v;
      }
      const span = Math.max(maxU - minU, maxV - minV, 1e-12);

      const baseVertex = vertCount;
      for (let j = 0; j < f.length; j++) {
        const pt = poly.vertices[f[j]];
        posList.push(pt[0] * scale, pt[1] * scale, pt[2] * scale);
        normList.push(fnorm[0], fnorm[1], fnorm[2]);
        const uNorm = (face2d[j][0] - minU) / span;
        const vNorm = 1.0 - ((face2d[j][1] - minV) / span);
        uvList.push(uNorm, vNorm);
        vertCount++;
      }

      if (f.length === 3) {
        idxList.push(baseVertex, baseVertex + 1, baseVertex + 2);
      } else {
        const localTris = earClipTriangulate(face2d);
        for (let j = 0; j < localTris.length; j++) {
          const [a, b, c] = localTris[j];
          idxList.push(baseVertex + a, baseVertex + b, baseVertex + c);
        }
      }
    }

    groupIdxArrays.push(new Uint32Array(idxList));
  }

  const posArray = new Float32Array(posList);
  const normArray = new Float32Array(normList);
  const uvArray = new Float32Array(uvList);
  // 8x8 neutral white PNG texture so baseColorFactor * baseColorTexture = baseColorFactor
  const pngBytes = encodePalettePNG(['#ffffff'], 8);

  // Compute exact Float32 min/max bounds for POSITION accessor (required by glTF 2.0 spec)
  const minPos = vertCount > 0 ? [Infinity, Infinity, Infinity] : [0, 0, 0];
  const maxPos = vertCount > 0 ? [-Infinity, -Infinity, -Infinity] : [0, 0, 0];
  for (let i = 0; i < vertCount; i++) {
    const px = posArray[i * 3];
    const py = posArray[(i * 3) + 1];
    const pz = posArray[(i * 3) + 2];
    if (px < minPos[0]) minPos[0] = px;
    if (py < minPos[1]) minPos[1] = py;
    if (pz < minPos[2]) minPos[2] = pz;
    if (px > maxPos[0]) maxPos[0] = px;
    if (py > maxPos[1]) maxPos[1] = py;
    if (pz > maxPos[2]) maxPos[2] = pz;
  }

  // Pack binary buffer views
  const posByteOffset = 0;
  const posByteLength = posArray.byteLength;

  const normByteOffset = posByteOffset + posByteLength;
  const normByteLength = normArray.byteLength;

  const uvByteOffset = normByteOffset + normByteLength;
  const uvByteLength = uvArray.byteLength;

  const bufferViews = [
    {
      buffer: 0,
      byteOffset: posByteOffset,
      byteLength: posByteLength,
      target: 34962 // ARRAY_BUFFER
    },
    {
      buffer: 0,
      byteOffset: normByteOffset,
      byteLength: normByteLength,
      target: 34962 // ARRAY_BUFFER
    },
    {
      buffer: 0,
      byteOffset: uvByteOffset,
      byteLength: uvByteLength,
      target: 34962 // ARRAY_BUFFER
    }
  ];

  const accessors = [
    {
      bufferView: 0,
      byteOffset: 0,
      componentType: 5126, // FLOAT
      count: vertCount,
      type: 'VEC3',
      min: minPos,
      max: maxPos
    },
    {
      bufferView: 1,
      byteOffset: 0,
      componentType: 5126, // FLOAT
      count: vertCount,
      type: 'VEC3'
    },
    {
      bufferView: 2,
      byteOffset: 0,
      componentType: 5126, // FLOAT
      count: vertCount,
      type: 'VEC2'
    }
  ];

  const primitives = [];
  const materials = [];
  const idxByteOffsets = [];
  let runningOffset = uvByteOffset + uvByteLength;

  for (let g = 0; g < groups.length; g++) {
    const grp = groups[g];
    const idxArr = groupIdxArrays[g];
    const bvIndex = bufferViews.length;
    const accIndex = accessors.length;

    idxByteOffsets.push(runningOffset);
    bufferViews.push({
      buffer: 0,
      byteOffset: runningOffset,
      byteLength: idxArr.byteLength,
      target: 34963 // ELEMENT_ARRAY_BUFFER
    });
    runningOffset += idxArr.byteLength;

    accessors.push({
      bufferView: bvIndex,
      byteOffset: 0,
      componentType: 5125, // UNSIGNED_INT
      count: idxArr.length,
      type: 'SCALAR'
    });

    materials.push({
      name: `FaceClass_${grp.fc}_${grp.hex}`,
      pbrMetallicRoughness: {
        baseColorTexture: {
          index: 0
        },
        baseColorFactor: grp.baseColorFactor,
        metallicFactor: 0.0,
        roughnessFactor: 0.55
      },
      doubleSided: true
    });

    primitives.push({
      attributes: {
        POSITION: 0,
        NORMAL: 1,
        TEXCOORD_0: 2
      },
      indices: accIndex,
      material: g,
      mode: 4
    });
  }

  const pngByteOffset = runningOffset;
  const pngByteLength = pngBytes.byteLength;
  const pngBvIndex = bufferViews.length;
  bufferViews.push({
    buffer: 0,
    byteOffset: pngByteOffset,
    byteLength: pngByteLength
  });

  const rawBinLength = pngByteOffset + pngByteLength;
  const paddedBinLength = (rawBinLength + 3) & ~3;

  const gltfJson = {
    asset: {
      version: '2.0',
      generator: 'Polyhedronisme'
    },
    scene: 0,
    scenes: [
      {
        name: poly.name || 'Polyhedron',
        nodes: [0]
      }
    ],
    nodes: [
      {
        name: poly.name || 'Polyhedron',
        mesh: 0
      }
    ],
    meshes: [
      {
        name: poly.name || 'Polyhedron',
        primitives
      }
    ],
    materials,
    textures: [
      {
        sampler: 0,
        source: 0
      }
    ],
    samplers: [
      {
        magFilter: 9728, // NEAREST
        minFilter: 9728, // NEAREST
        wrapS: 33071,    // CLAMP_TO_EDGE
        wrapT: 33071     // CLAMP_TO_EDGE
      }
    ],
    images: [
      {
        bufferView: pngBvIndex,
        mimeType: 'image/png'
      }
    ],
    accessors,
    bufferViews,
    buffers: [
      {
        byteLength: paddedBinLength
      }
    ]
  };

  const jsonBytes = new TextEncoder().encode(JSON.stringify(gltfJson));
  const paddedJsonLength = (jsonBytes.byteLength + 3) & ~3;

  const totalByteLength = 12 + 8 + paddedJsonLength + 8 + paddedBinLength;
  const glbBuffer = new ArrayBuffer(totalByteLength);
  const glbBytes = new Uint8Array(glbBuffer);
  const glbView = new DataView(glbBuffer);

  // 12-byte GLB header
  glbView.setUint32(0, 0x46546c67, true); // 'glTF'
  glbView.setUint32(4, 2, true);          // version 2
  glbView.setUint32(8, totalByteLength, true);

  // Chunk 0: JSON (padded with 0x20 spaces)
  glbView.setUint32(12, paddedJsonLength, true);
  glbView.setUint32(16, 0x4e4f534a, true); // 'JSON'
  glbBytes.fill(0x20, 20, 20 + paddedJsonLength);
  glbBytes.set(jsonBytes, 20);

  // Chunk 1: BIN (padded with 0x00)
  const binChunkHeaderOffset = 20 + paddedJsonLength;
  glbView.setUint32(binChunkHeaderOffset, paddedBinLength, true);
  glbView.setUint32(binChunkHeaderOffset + 4, 0x004e4942, true); // 'BIN\0'

  const binDataOffset = binChunkHeaderOffset + 8;
  glbBytes.set(new Uint8Array(posArray.buffer), binDataOffset + posByteOffset);
  glbBytes.set(new Uint8Array(normArray.buffer), binDataOffset + normByteOffset);
  glbBytes.set(new Uint8Array(uvArray.buffer), binDataOffset + uvByteOffset);
  for (let g = 0; g < groups.length; g++) {
    glbBytes.set(new Uint8Array(groupIdxArrays[g].buffer), binDataOffset + idxByteOffsets[g]);
  }
  glbBytes.set(pngBytes, binDataOffset + pngByteOffset);

  return glbBuffer;
};


